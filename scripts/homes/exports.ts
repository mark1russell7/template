// Writes the index of the exports of the home packages: packages/conventions/src/home-exports.ts.
// The rule home-package of conventions reads it. A function of a repository with the name of an export
// of another home is a copy that belongs in that home (STRATEGY direction 18, the map of homes).
//
//   node scripts/homes/exports.ts [--check]
//
// For each package of a published home of the map, the script takes the tarball of its latest version
// from npm, and reads the names of its exports with packageReport of @mark1russell7/api-report. Thus
// the index is the published API, not the source of a branch. --check exits 1 when the index is not
// current: a home has new exports, lost exports, or is new or gone. A new version with the same names is
// current, so a release of conventions itself (which is in the index) does not make the index old.
// Run it again after each release of a home package that changes its exports.
//
// A home that changes its names on npm gets GRACE_DAYS. The grace starts at the publish time of the first version
// after the version of the index with other names. A later version with the same names does not start it. In the
// grace, --check passes with a warning, and writes stale=true to GITHUB_OUTPUT. Thus one refresh of the index takes
// the releases of a week, and main stays green. A package that is new or gone fails at once: only a change of the
// map in this repository makes it. A package with no publish time on npm also fails.
//
// Only the map decides which packages the index has (indexPackages). The job of homes-npm.yml reads npm, so it does not
// run on a pull request. A test of exports.test.ts holds the keys of the index to the map with no read of npm, so a pull
// request that adds a published home to the map with no row in the index fails its own checks.
import { execFileSync } from "node:child_process";
import { appendFileSync, mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { packageReport } from "@mark1russell7/api-report";
import { type Home, HOMES } from "../../packages/conventions/src/map.ts";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
export const INDEX_FILE: string = join(ROOT, "packages/conventions/src/home-exports.ts");

/** The exports of one home package at one version. */
export interface PackageExports {
  readonly version: string;
  readonly names: readonly string[];
}

/**
 * This function gives the packages of the index, in the order of the map: each package of a published home that is not
 * pending. Only the map decides this list, so a test holds the keys of the index to it with no read of npm.
 */
export function indexPackages(homes: readonly Home[]): string[] {
  return homes.filter((home) => home.state === "published").flatMap((home) => home.packages.filter((name) => !(home.pending ?? []).includes(name)));
}

/** This function gives the names of the values of an API report: no types, and no `default`. */
export function valueNames(report: string): string[] {
  const names = new Set<string>();
  for (const line of report.split("\n")) {
    const match = /^([A-Za-z_$][\w$]*): /.exec(line);
    if (match?.[1] !== undefined && match[1] !== "default") names.add(match[1]);
  }
  return [...names].sort();
}

/** This function gives the text of the index module. */
export function indexModule(index: Readonly<Record<string, PackageExports>>): string {
  const lines = [
    "// Generated by scripts/homes/exports.ts from the latest version of each home package on npm. Do not edit by hand.",
    "/** The names of the values that each home package exports, with the version that the names come from. */",
    "export const HOME_EXPORTS: Readonly<Record<string, { readonly version: string; readonly names: readonly string[] }>> = {",
  ];
  for (const name of Object.keys(index).sort()) {
    const entry = index[name];
    if (entry === undefined) continue;
    lines.push(`  ${JSON.stringify(name)}: { version: ${JSON.stringify(entry.version)}, names: ${JSON.stringify(entry.names)} },`);
  }
  lines.push("};", "");
  return lines.join("\n");
}

/** One version of a package from npm, unpacked: the version, and the folder of its files (the folder `package` of the tarball). */
export interface UnpackedPackage {
  readonly version: string;
  readonly dir: string;
}

/** This function takes the tarball of a version of a package from npm, and unpacks it in a new folder of `temp`. */
export async function unpackPackage(name: string, spec: string, temp: string): Promise<UnpackedPackage> {
  const response = await fetch(`https://registry.npmjs.org/${encodeURIComponent(name)}/${spec}`);
  if (!response.ok) throw new Error(`${name}@${spec}: npm gives HTTP ${response.status}`);
  const meta = (await response.json()) as { version: string; dist: { tarball: string } };
  const tarball = await fetch(meta.dist.tarball);
  if (!tarball.ok) throw new Error(`${name}@${spec}: the tarball gives HTTP ${tarball.status}`);
  const dir = join(temp, `${name.replace(/[@/]/g, "_")}_${spec}`);
  mkdirSync(dir, { recursive: true });
  const file = join(dir, "package.tgz");
  writeFileSync(file, Buffer.from(await tarball.arrayBuffer()));
  execFileSync("tar", ["-xzf", "package.tgz"], { cwd: dir, stdio: "ignore" });
  return { version: meta.version, dir: join(dir, "package") };
}

async function exportsOf(name: string, spec: string, temp: string): Promise<PackageExports> {
  const unpacked = await unpackPackage(name, spec, temp);
  return { version: unpacked.version, names: valueNames(packageReport(unpacked.dir)) };
}

/** This function gives the names of each package of an index module, keyed by the package, with no version. */
export function namesOf(text: string): Map<string, string> {
  const names = new Map<string, string>();
  for (const match of text.matchAll(/^ {2}("[^"]+"): \{ version: "[^"]*", names: (\[.*\]) \},$/gm)) names.set(JSON.parse(match[1]!) as string, match[2]!);
  return names;
}

/** This function gives the version of each package of an index module, keyed by the package. */
export function versionsOf(text: string): Map<string, string> {
  const versions = new Map<string, string>();
  for (const match of text.matchAll(/^ {2}("[^"]+"): \{ version: "([^"]*)", names: \[.*\] \},$/gm)) versions.set(JSON.parse(match[1]!) as string, match[2]!);
  return versions;
}

/**
 * The days that a home can have new names on npm before the check fails. This grace is a tolerance. In it, a release
 * of conventions can carry an index up to 7 days old, and the rule home-package misses the new names of a home.
 * The grace ends when the job opens the pull request of the refresh itself, with a token that starts CI. Then the
 * grace goes to 1 day, or goes away.
 */
export const GRACE_DAYS: number = 7;

const DAY_MS = 24 * 60 * 60 * 1000;

/**
 * This function gives the versions after a version up to the latest version, from the field time of npm. The order
 * is the order of their publish times. It gives no pre-release. It gives an empty list when npm has no time for a version.
 */
export function laterVersions(time: Readonly<Record<string, string>>, version: string, latest: string): string[] {
  const start = time[version];
  const end = time[latest];
  if (start === undefined || end === undefined) return [];
  const from = Date.parse(start);
  const to = Date.parse(end);
  return Object.entries(time)
    .filter(([key]) => key !== "created" && key !== "modified" && (key === latest || !key.includes("-")))
    .filter(([, value]) => Date.parse(value) > from && Date.parse(value) <= to)
    .sort(([, a], [, b]) => Date.parse(a) - Date.parse(b))
    .map(([key]) => key);
}

/** The verdict of the check: the packages that fail, and the packages in their grace, with its end. */
export interface Verdict {
  readonly fail: readonly string[];
  readonly grace: readonly { readonly name: string; readonly ends: string }[];
}

/**
 * This function gives the verdict for the changed packages. The grace of a package of both indexes starts at its
 * time in starts: the first version with other names. A new or gone package, or a package with no start, fails.
 */
export function verdictOf(
  current: string,
  next: string,
  changed: readonly string[],
  starts: ReadonlyMap<string, string>,
  now: Date,
  graceDays: number = GRACE_DAYS,
): Verdict {
  const before = versionsOf(current);
  const after = versionsOf(next);
  const fail: string[] = [];
  const grace: { name: string; ends: string }[] = [];
  for (const name of changed) {
    const start = before.has(name) && after.has(name) ? starts.get(name) : undefined;
    const ends = start === undefined ? undefined : Date.parse(start) + graceDays * DAY_MS;
    if (ends !== undefined && ends > now.getTime()) grace.push({ name, ends: new Date(ends).toISOString() });
    else fail.push(name);
  }
  return { fail, grace };
}

async function timesOf(name: string): Promise<Readonly<Record<string, string>> | undefined> {
  const response = await fetch(`https://registry.npmjs.org/${encodeURIComponent(name)}`);
  if (!response.ok) return undefined;
  return ((await response.json()) as { time?: Record<string, string> }).time;
}

/** This function gives the packages whose names differ between two index modules, in order: new, gone or changed. */
export function changedPackages(current: string, next: string): string[] {
  const before = namesOf(current);
  const after = namesOf(next);
  return [...new Set([...before.keys(), ...after.keys()])].filter((name) => before.get(name) !== after.get(name)).sort();
}

/** This function tells if two lists have the same names, in any order. */
export function sameNames(a: readonly string[], b: readonly string[]): boolean {
  if (a.length !== b.length) return false;
  const left = [...a].sort();
  const right = [...b].sort();
  return left.every((name, i) => name === right[i]);
}

/**
 * This function gives the publish time of the first version after the version of the index with other names. It
 * reads the names of each version with namesAt, in the order of the publish times, and stops at the first change.
 * It gives undefined when no later version has other names. An error of namesAt goes to the caller, so the check fails.
 */
export async function firstChange(
  time: Readonly<Record<string, string>>,
  version: string,
  latest: string,
  names: readonly string[],
  namesAt: (version: string) => Promise<readonly string[]>,
): Promise<string | undefined> {
  for (const candidate of laterVersions(time, version, latest)) {
    if (!sameNames(await namesAt(candidate), names)) return time[candidate];
  }
  return undefined;
}

async function changeStart(name: string, version: string, latest: PackageExports, names: readonly string[], temp: string): Promise<string | undefined> {
  const time = await timesOf(name);
  if (time === undefined) return undefined;
  return firstChange(time, version, latest.version, names, async (candidate) => (candidate === latest.version ? latest.names : (await exportsOf(name, candidate, temp)).names));
}

async function main(args: readonly string[]): Promise<number> {
  const temp = mkdtempSync(join(tmpdir(), "home-exports-"));
  try {
    return await mainIn(args, temp);
  } finally {
    rmSync(temp, { recursive: true, force: true });
  }
}

async function mainIn(args: readonly string[], temp: string): Promise<number> {
  const check = args.includes("--check");
  const index: Record<string, PackageExports> = {};
  for (const name of indexPackages(HOMES)) index[name] = await exportsOf(name, "latest", temp);
  const next = indexModule(index);
  let current = "";
  try {
    current = readFileSync(INDEX_FILE, "utf8");
  } catch {
    // No index yet
  }
  if (check) {
    const changed = changedPackages(current, next);
    if (changed.length === 0) return 0;
    const versions = versionsOf(current);
    const names = namesOf(current);
    const starts = new Map<string, string>();
    for (const name of changed) {
      const version = versions.get(name);
      const latest = index[name];
      const before = names.get(name);
      if (version === undefined || latest === undefined || before === undefined) continue;
      const start = await changeStart(name, version, latest, JSON.parse(before) as string[], temp);
      if (start !== undefined) starts.set(name, start);
    }
    const verdict = verdictOf(current, next, changed, starts, new Date());
    for (const { name, ends } of verdict.grace) {
      process.stdout.write(`::warning::The index has old names of ${name}. The check fails from ${ends}. Run node scripts/homes/exports.ts\n`);
    }
    const output = process.env["GITHUB_OUTPUT"];
    if (verdict.grace.length > 0 && output !== undefined) appendFileSync(output, "stale=true\n");
    if (verdict.fail.length === 0) return 0;
    process.stderr.write(`packages/conventions/src/home-exports.ts is not current: the names of ${verdict.fail.length} package(s) changed on npm (${verdict.fail.join(", ")}). Run node scripts/homes/exports.ts\n`);
    return 1;
  }
  writeFileSync(INDEX_FILE, next);
  const count = Object.values(index).reduce((sum, entry) => sum + entry.names.length, 0);
  process.stdout.write(`${Object.keys(index).length} packages, ${count} names: packages/conventions/src/home-exports.ts\n`);
  return 0;
}

if (process.argv[1] !== undefined && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  process.exitCode = await main(process.argv.slice(2));
}
