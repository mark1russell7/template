// Writes the index of the exports of the home packages: packages/conventions/src/home-exports.ts.
// The rule home-package of conventions reads it. A function of a repository with the name of an export
// of another home is a copy that belongs in that home (STRATEGY direction 18, the map of homes).
//
//   node scripts/homes/exports.ts [--check]
//
// For each package of a published home of the map, the script takes the tarball of its latest version
// from npm, and reads the names of its exports with packageReport of @mark1russell7/api-report. Thus
// the index is the published API, not the source of a branch. --check exits 1 when the index is not
// current: a home has a new version or new exports. Run it again after each release of a home package.
import { execFileSync } from "node:child_process";
import { mkdirSync, mkdtempSync, readFileSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { packageReport } from "@mark1russell7/api-report";
import { HOMES } from "../../packages/conventions/src/map.ts";

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
export const INDEX_FILE: string = join(ROOT, "packages/conventions/src/home-exports.ts");

/** The exports of one home package at one version. */
export interface PackageExports {
  readonly version: string;
  readonly names: readonly string[];
}

/** This function gives the names of the values of an API report: no types, and no `default`. */
export function valueNames(report: string): string[] {
  const names = new Set<string>();
  for (const line of report.split("\n")) {
    const match = /^([A-Za-z_$][\w$]*): /.exec(line);
    if (match?.[1] !== undefined && match[1] !== "default") names.add(match[1]);
  }
  return [...names].sort();
}

/** This function gives the text of the index module. */
export function indexModule(index: Readonly<Record<string, PackageExports>>): string {
  const lines = [
    "// Generated by scripts/homes/exports.ts from the latest version of each home package on npm. Do not edit by hand.",
    "/** The names of the values that each home package exports, with the version that the names come from. */",
    "export const HOME_EXPORTS: Readonly<Record<string, { readonly version: string; readonly names: readonly string[] }>> = {",
  ];
  for (const name of Object.keys(index).sort()) {
    const entry = index[name];
    if (entry === undefined) continue;
    lines.push(`  ${JSON.stringify(name)}: { version: ${JSON.stringify(entry.version)}, names: ${JSON.stringify(entry.names)} },`);
  }
  lines.push("};", "");
  return lines.join("\n");
}

async function exportsOf(name: string, temp: string): Promise<PackageExports> {
  const response = await fetch(`https://registry.npmjs.org/${encodeURIComponent(name)}/latest`);
  if (!response.ok) throw new Error(`${name}: npm gives HTTP ${response.status}`);
  const meta = (await response.json()) as { version: string; dist: { tarball: string } };
  const tarball = await fetch(meta.dist.tarball);
  if (!tarball.ok) throw new Error(`${name}: the tarball gives HTTP ${tarball.status}`);
  const dir = join(temp, name.replace(/[@/]/g, "_"));
  mkdirSync(dir, { recursive: true });
  const file = join(dir, "package.tgz");
  writeFileSync(file, Buffer.from(await tarball.arrayBuffer()));
  execFileSync("tar", ["-xzf", "package.tgz"], { cwd: dir, stdio: "ignore" });
  return { version: meta.version, names: valueNames(packageReport(join(dir, "package"))) };
}

async function main(args: readonly string[]): Promise<number> {
  const check = args.includes("--check");
  const temp = mkdtempSync(join(tmpdir(), "home-exports-"));
  const index: Record<string, PackageExports> = {};
  try {
    for (const home of HOMES) {
      if (home.state !== "published") continue;
      for (const name of home.packages) index[name] = await exportsOf(name, temp);
    }
  } finally {
    rmSync(temp, { recursive: true, force: true });
  }
  const next = indexModule(index);
  let current = "";
  try {
    current = readFileSync(INDEX_FILE, "utf8");
  } catch {
    // No index yet
  }
  if (check) {
    if (current === next) return 0;
    process.stderr.write("packages/conventions/src/home-exports.ts is not current. Run node scripts/homes/exports.ts\n");
    return 1;
  }
  writeFileSync(INDEX_FILE, next);
  const count = Object.values(index).reduce((sum, entry) => sum + entry.names.length, 0);
  process.stdout.write(`${Object.keys(index).length} packages, ${count} names: packages/conventions/src/home-exports.ts\n`);
  return 0;
}

if (process.argv[1] !== undefined && realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url))) {
  process.exitCode = await main(process.argv.slice(2));
}
